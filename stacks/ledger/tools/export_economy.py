#!/usr/bin/env python3
"""Exports Ledger's economy.xlsx to data/economy.dta (game-stacks.md §4.2).

The spreadsheet is the designers' harness, kept first-class: this script turns its Goods and
Buildings sheets into data, with an #origin declaration, so Baker's source() names the sheet
behind every number and `reference` lists the tool. Each line ends with the sheet row it
came from, so a tuned value in agent.dta can be reported as the cell to change.

    python3 -I stacks/ledger/tools/export_economy.py            # writes data/economy.dta
    python3 -I stacks/ledger/tools/export_economy.py --check    # exit 1 if it is stale

Standard library only: an .xlsx is a zip of XML.
"""
import argparse
import pathlib
import re
import sys
import zipfile
import xml.etree.ElementTree as ET

NS = {"m": "http://schemas.openxmlformats.org/spreadsheetml/2006/main",
      "r": "http://schemas.openxmlformats.org/officeDocument/2006/relationships"}
REL = "{http://schemas.openxmlformats.org/officeDocument/2006/relationships}id"
HERE = pathlib.Path(__file__).resolve().parent.parent


def column(ref):
    n = 0
    for ch in re.match(r"[A-Z]+", ref).group(0):
        n = n * 26 + ord(ch) - 64
    return n - 1


def sheets(path):
    """{sheet name: [rows]}, each row a list of cell values (str, int, float, or None)."""
    with zipfile.ZipFile(path) as z:
        shared = []
        if "xl/sharedStrings.xml" in z.namelist():
            for si in ET.fromstring(z.read("xl/sharedStrings.xml")).findall("m:si", NS):
                shared.append("".join(t.text or "" for t in si.iter("{%s}t" % NS["m"])))
        rels = {r.get("Id"): r.get("Target") for r in
                ET.fromstring(z.read("xl/_rels/workbook.xml.rels"))}
        out = {}
        for s in ET.fromstring(z.read("xl/workbook.xml")).find("m:sheets", NS):
            target = rels[s.get(REL)].lstrip("/")
            target = target if target.startswith("xl/") else "xl/" + target
            rows = []
            for row in ET.fromstring(z.read(target)).iter("{%s}row" % NS["m"]):
                cells = {}
                for c in row.findall("m:c", NS):
                    kind, v = c.get("t"), c.find("m:v", NS)
                    if kind == "s":
                        value = shared[int(v.text)]
                    elif kind == "inlineStr":
                        value = "".join(t.text or "" for t in c.iter("{%s}t" % NS["m"]))
                    elif v is None:
                        value = None
                    else:
                        f = float(v.text)
                        value = int(f) if f.is_integer() else f
                    cells[column(c.get("r"))] = value
                rows.append([cells.get(i) for i in range(max(cells, default=-1) + 1)])
            out[s.get("name")] = rows
        return out


def number(v):
    return str(v) if not isinstance(v, float) else ("%.6g" % v)


def table(rows, sheet, fields, extra=None):
    """(name (field value) ...) per data row, keyed by the first column."""
    header = [str(h or "").strip() for h in rows[0]]
    lines = []
    for i, row in enumerate(rows[1:], start=2):
        cell = dict(zip(header, row))
        name = str(cell.get("name") or "").strip()
        if not name:
            continue
        parts = []
        for f in fields:
            v = cell.get(f)
            if v is None or v == "":
                continue
            parts.append("(%s %s)" % (f, number(v)))
        if extra:
            parts += extra(cell)
        lines.append("   (%s %s)   ; %s, row %d" % (name, " ".join(parts), sheet, i))
    return lines


def building_extra(cell):
    parts = []
    recipe = str(cell.get("recipe") or "").strip()
    if recipe:
        parts.append("(recipe %s)" % recipe)
    unlock = str(cell.get("unlock") or "").strip()
    if unlock:
        parts.append("(unlock %s)" % unlock)
    return parts


def export(xlsx):
    book = sheets(xlsx)
    for need in ("Goods", "Buildings"):
        if need not in book:
            sys.exit("%s has no sheet named %s" % (xlsx, need))
    out = ["; Generated by tools/export_economy.py from economy.xlsx. Do not edit: change the",
           "; sheet and export again. To try a value, set it in agent.dta and report the cell",
           "; named at the end of its line.",
           '#origin ("economy.xlsx" (tool sheets-export))',
           "",
           "(goods"]
    out += table(book["Goods"], "Goods", ["base_price", "demand", "spoil_days", "volatility"])
    out.append(")")
    out.append("")
    out.append("(buildings")
    out += table(book["Buildings"], "Buildings", ["cost", "upkeep", "rate"], building_extra)
    out.append(")")
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--xlsx", default=str(HERE / "economy.xlsx"))
    ap.add_argument("--out", default=str(HERE / "data" / "economy.dta"))
    ap.add_argument("--check", action="store_true", help="exit 1 if --out is not up to date")
    a = ap.parse_args()
    text = export(a.xlsx)
    out = pathlib.Path(a.out)
    if a.check:
        current = out.read_text() if out.exists() else ""
        if current != text:
            print("%s is stale: run tools/export_economy.py" % out, file=sys.stderr)
            return 1
        return 0
    out.write_text(text)
    print("wrote %s" % out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
